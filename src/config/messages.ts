/** 이전 인덱스와 중복되지 않는 랜덤 메시지 반환 */
export function getRandomMessage(messages: readonly string[], prevIndex: number): [string, number] {
  let idx: number;
  do {
    idx = Math.floor(Math.random() * messages.length);
  } while (idx === prevIndex && messages.length > 1);
  return [messages[idx], idx];
}
